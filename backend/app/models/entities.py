from datetime import datetime

from sqlalchemy import (
    Boolean,
    Column,
    DateTime,
    Float,
    ForeignKey,
    Integer,
    String,
    Text,
)
from sqlalchemy.orm import relationship

from app.core.database import Base


# 1. Users: Field Officers and Branch Managers
class User(Base):
    __tablename__ = "users"

    id = Column(Integer, primary_key=True, index=True)

    full_name = Column(String(100), nullable=False)
    email = Column(String(150), unique=True, index=True, nullable=False)
    hashed_password = Column(String(255), nullable=False)

    role = Column(String(30), nullable=False)
    branch = Column(String(100), nullable=True)
    is_active = Column(Boolean, default=True)

    created_at = Column(DateTime, default=datetime.utcnow)

    assigned_loans = relationship(
        "Loan",
        back_populates="officer"
    )

    activities = relationship(
        "CollectionActivity",
        back_populates="officer"
    )


# 2. Loans: Borrower and overdue loan information
class Loan(Base):
    __tablename__ = "loans"

    id = Column(Integer, primary_key=True, index=True)

    loan_id = Column(String(50), unique=True, index=True, nullable=False)

    borrower_name = Column(String(150), nullable=False)
    business_type = Column(String(100), nullable=True)
    phone_number = Column(String(20), nullable=True)
    pincode = Column(String(10), nullable=True)

    outstanding_amount = Column(Float, nullable=False)
    dpd = Column(Integer, default=0)

    due_date = Column(DateTime, nullable=True)
    promise_date = Column(DateTime, nullable=True)

    status = Column(String(30), default="overdue")

    # Explainable AI priority score
    priority_score = Column(Float, default=0)
    priority_reasons = Column(Text, nullable=True)

    assigned_officer_id = Column(
        Integer,
        ForeignKey("users.id"),
        nullable=True
    )

    created_at = Column(DateTime, default=datetime.utcnow)
    updated_at = Column(
        DateTime,
        default=datetime.utcnow,
        onupdate=datetime.utcnow
    )

    officer = relationship(
        "User",
        back_populates="assigned_loans"
    )

    promises = relationship(
        "PromiseToPay",
        back_populates="loan",
        cascade="all, delete-orphan"
    )

    activities = relationship(
        "CollectionActivity",
        back_populates="loan",
        cascade="all, delete-orphan"
    )


# 3. Promise to Pay: Borrower's payment commitments
class PromiseToPay(Base):
    __tablename__ = "promises_to_pay"

    id = Column(Integer, primary_key=True, index=True)

    loan_id = Column(
        Integer,
        ForeignKey("loans.id"),
        nullable=False
    )

    promised_amount = Column(Float, nullable=False)
    promised_date = Column(DateTime, nullable=False)

    status = Column(String(30), default="pending")
    # pending, fulfilled, broken, cancelled

    reminder_sent = Column(Boolean, default=False)

    created_at = Column(DateTime, default=datetime.utcnow)
    updated_at = Column(
        DateTime,
        default=datetime.utcnow,
        onupdate=datetime.utcnow
    )

    loan = relationship(
        "Loan",
        back_populates="promises"
    )


# 4. Collection Activities: Calls, visits and payment outcomes
class CollectionActivity(Base):
    __tablename__ = "collection_activities"

    id = Column(Integer, primary_key=True, index=True)

    # Unique ID generated by the mobile device.
    # Helps prevent duplicate records during offline sync.
    client_event_id = Column(
        String(100),
        unique=True,
        index=True,
        nullable=False
    )

    loan_id = Column(
        Integer,
        ForeignKey("loans.id"),
        nullable=False
    )

    officer_id = Column(
        Integer,
        ForeignKey("users.id"),
        nullable=False
    )

    activity_type = Column(String(30), nullable=False)
    outcome = Column(String(30), nullable=False)

    notes = Column(Text, nullable=True)

    latitude = Column(Float, nullable=True)
    longitude = Column(Float, nullable=True)

    occurred_at = Column(DateTime, nullable=False)
    created_at = Column(DateTime, default=datetime.utcnow)

    synced = Column(Boolean, default=True)

    loan = relationship(
        "Loan",
        back_populates="activities"
    )

    officer = relationship(
        "User",
        back_populates="activities"
    )